"""Builds the NEW logo as clean SVG (no fonts, no gradients) from the client's artwork.
Colours are sampled from the original: blue #2E3192, red #ED1B24, green #00A74F.
Output: prototype/assets/new-logo.svg (mark + wordmark), new-mark.svg (blades only), new-wordmark.svg."""
import math
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
BLUE, RED, GREEN = '#2E3192', '#ED1B24', '#00A74F'
C = 50.0
def pt(r, a): return (C + r * math.cos(a), C + r * math.sin(a))
def blade(phi_deg, R=45.5, n=44):
    """Crescent blade. Outer edge follows the ring and curls inward at the thin tail; inner edge is offset by a tapering thickness."""
    a0, a1 = math.radians(phi_deg - 74), math.radians(phi_deg + 28)
    outer, inner = [], []
    for i in range(n + 1):
        t = i / n; a = a0 + (a1 - a0) * t
        ro = R * (1 - 0.30 * (1 - t) ** 2.1)
        th = 11.0 * (math.sin(math.pi * t ** 0.85) ** 0.95)
        outer.append(pt(ro, a)); inner.append(pt(ro - th, a))
    return outer + inner[::-1][1:-1]
def smooth(points):
    """Closed Catmull-Rom spline to cubic Bezier path."""
    n = len(points); d = f"M{points[0][0]:.2f} {points[0][1]:.2f}"
    for i in range(n):
        p0, p1, p2, p3 = points[(i - 1) % n], points[i], points[(i + 1) % n], points[(i + 2) % n]
        c1 = (p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6); c2 = (p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6)
        d += f"C{c1[0]:.2f} {c1[1]:.2f} {c2[0]:.2f} {c2[1]:.2f} {p2[0]:.2f} {p2[1]:.2f}"
    return d + "Z"
def blade_path(phi):
    pts = blade(phi); # remove duplicate tip points to keep sharp tips
    return smooth(pts)
import json as _j
_tr = _j.load(open('scripts/blades-traced.json'))  # traced from the client artwork by scripts/trace-logo.py
class _B: pass
order = [(i, t['color']) for i, t in enumerate(_tr)]
def blade_path(i): return smooth(_tr[i]['pts'])
blades = ''.join(f'<path d="{blade_path(p)}" fill="{c}"/>' for p, c in order)
# Wordmark from Liberation Sans Bold, set tight like the original
font = TTFont('/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf'); gs = font.getGlyphSet(); cmap = font.getBestCmap(); upm = font['head'].unitsPerEm
cap = font['OS/2'].sCapHeight; scale = 19.0 / cap; track = -0.07 * upm
x = 0; parts = []
for ch in 'NEW':
    g = cmap[ord(ch)]; pen = SVGPathPen(gs); tp = TransformPen(pen, (scale, 0, 0, -scale, x * scale, 0)); gs[g].draw(tp); parts.append(pen.getCommands()); x += gs[g].width + track
total = (x - track) * scale
tx = C - total / 2; ty = C + 9.5
word = f'<g transform="translate({tx:.2f} {ty:.2f})" fill="#111111"><path d="{" ".join(parts)}"/></g>'
def svg(body, vb='0 0 100 100'): return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{vb}" role="img" aria-label="NEW">{body}</svg>\n'
open('prototype/assets/new-logo.svg', 'w').write(svg(blades + word))
open('prototype/assets/new-mark.svg', 'w').write(svg(blades))
open('prototype/assets/new-wordmark.svg', 'w').write(svg(f'<g transform="translate({-tx + 2:.2f} {-ty + 24:.2f})"></g>' + f'<g transform="translate({2 - 0:.2f} 24)" fill="#111111"><path d="{" ".join(parts)}"/></g>', f'0 0 {total + 4:.2f} 30'))
open('prototype/shared/logo-parts.json', 'w').write('{"blades": %s, "word": %s, "order": %s}' % (__import__('json').dumps([blade_path(p) for p, c in order]), __import__('json').dumps(' '.join(parts)), __import__('json').dumps([c for p, c in order])))
print('written', round(total, 1), 'wide wordmark')

# ---- JS module and generated CSS (faint blade watermark for header bands)
import json, urllib.parse
blades_only = ''.join(f'<path d="{blade_path(p)}" fill="{c}"/>' for p, c in order)
js = f"""/* NEW logo (generated by scripts/build-logo.py). Colours from the client artwork: blue {BLUE}, red {RED}, green {GREEN}. */
(function () {{
  const BLADES = {json.dumps(blades_only)}, WORD = {json.dumps(' '.join(parts))}, TX = {tx:.2f}, TY = {ty:.2f};
  const svg = (inner, w, h, vb, label) => '<svg class="logo" xmlns="http://www.w3.org/2000/svg" viewBox="' + (vb || '0 0 100 100') + '" width="' + w + '" height="' + (h || w) + '" role="img" aria-label="' + (label || 'NEW') + '">' + inner + '</svg>';
  window.AC = window.AC || {{}};
  AC.logo = {{
    mark: s => svg(BLADES, s, s),
    full: s => svg(BLADES + '<g transform="translate(' + TX + ' ' + TY + ')" style="fill:var(--logo-ink,#111111)"><path d="' + WORD + '"/></g>', s, s),
    /* White rounded tile so the blue blades stay readable on dark backgrounds */
    tile: (s, full) => '<span class="logo-tile" style="width:' + s + 'px;height:' + s + 'px;border-radius:' + Math.round(s * 0.28) + 'px">' + (full ? AC.logo.full(Math.round(s * 0.9)) : AC.logo.mark(Math.round(s * 0.78))) + '</span>'
  }};
}})();
"""
open('prototype/shared/logo.js', 'w').write(js)
wm = urllib.parse.quote(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">{blades_only.replace(BLUE, "#FFFFFF").replace(RED, "#FFFFFF").replace(GREEN, "#FFFFFF")}</svg>', safe="")
css_block = f"""/* BRAND-GENERATED START (scripts/build-logo.py) */
.band::before {{ content: ''; position: absolute; right: -56px; top: 8px; width: 250px; height: 250px; border-radius: 0; background: url("data:image/svg+xml,{wm}") no-repeat center / contain; opacity: .07; }}
.logo-tile {{ display: inline-grid; place-items: center; background: #fff; flex: none; box-shadow: inset 0 1px 0 #fff, 0 4px 10px rgba(21,24,88,.22); }}
/* BRAND-GENERATED END */"""
b = open('prototype/shared/base.css').read()
import re
if '/* BRAND-GENERATED START' in b:
    b = re.sub(r'/\* BRAND-GENERATED START.*?BRAND-GENERATED END \*/', css_block.replace('\\','\\\\'), b, flags=re.S)
else:
    b += '\n' + css_block + '\n'
open('prototype/shared/base.css', 'w').write(b)
print('logo.js and css block written')
